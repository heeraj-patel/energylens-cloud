package reports

import (
	"bytes"
	_ "embed"
	"html"
	"regexp"
	"strings"

	"github.com/go-pdf/fpdf"
)

//go:embed fonts/source-sans-3-variable.ttf
var reportFont []byte

var reportBlockEnd = regexp.MustCompile(`(?i)</(?:h[1-6]|p|li|ul|ol|section)>`)
var reportHead = regexp.MustCompile(`(?is)<head\b[^>]*>.*?</head>`)
var reportTags = regexp.MustCompile(`<[^>]*>`)

// RenderApprovedPDF renders the same fixed report text as the email renderer.
// It uses the complete typed v1/v2 report on Cloud instead of Mobile's
// intentionally abbreviated preview model.
func RenderApprovedPDF(preview Preview, digest string) ([]byte, error) {
	rendered, err := RenderApprovedHTML(preview, digest)
	if err != nil {
		return nil, err
	}
	text := reportPDFText(rendered.HTML)
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(17, 18, 17)
	pdf.SetAutoPageBreak(true, 18)
	pdf.SetTitle(rendered.Subject, true)
	pdf.SetAuthor("EnergyLens", true)
	pdf.AddUTF8FontFromBytes("SourceSans3", "", reportFont)
	pdf.AddPage()
	pdf.SetFont("SourceSans3", "", 10)
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			pdf.Ln(2)
			continue
		}
		if line == "EnergyLens report" {
			pdf.SetFont("SourceSans3", "", 20)
			pdf.SetTextColor(0, 91, 120)
		} else if line == "Approved snapshot" || line == "Selected appliances" ||
			line == "Available recommendations" || line == "Scope and assumptions" {
			pdf.Ln(3)
			pdf.SetFont("SourceSans3", "", 14)
			pdf.SetTextColor(0, 91, 120)
		} else {
			pdf.SetFont("SourceSans3", "", 10)
			pdf.SetTextColor(17, 27, 47)
		}
		pdf.MultiCell(0, 5, line, "", "L", false)
	}
	var output bytes.Buffer
	if err := pdf.Output(&output); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

func reportPDFText(reportHTML string) string {
	// The HTML is generated by our fixed, autoescaping report template.
	plain := reportBlockEnd.ReplaceAllString(reportHead.ReplaceAllString(reportHTML, ""), "\n")
	plain = reportTags.ReplaceAllString(plain, "")
	plain = html.UnescapeString(plain)
	lines := make([]string, 0)
	for _, line := range strings.Split(plain, "\n") {
		line = strings.Join(strings.Fields(line), " ")
		if line != "" {
			lines = append(lines, line)
		}
	}
	return strings.Join(lines, "\n")
}
